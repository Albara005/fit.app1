#!/usr/bin/env node
// Deno needs explicit file extensions; Metro and Vitest do not. Rather than keep
// two copies of the safety gate and watch them drift, the edge function's copy
// is generated from lib/ with extensions rewritten in. `npm test` fails if the
// generated tree is stale, so the copy can never quietly fall behind.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const outDir = join(root, 'supabase/functions/_shared/lib')

const SOURCES = [
  'lib/types.ts',
  'lib/privacy/modelSafe.ts',
  'lib/safety/text.ts',
  'lib/safety/allergens.ts',
  'lib/safety/patterns.ts',
  'lib/safety/substitute.ts',
  'lib/safety/gate.ts',
  'lib/plan/exercises.ts',
  'lib/plan/nutrition.ts',
  'lib/plan/rng.ts',
  'lib/plan/split.ts',
  'lib/plan/engine.ts',
  'lib/nutrition/dishes.ts',
]

const HEADER = '// GENERATED by scripts/sync-edge-safety.mjs — edit lib/ instead.\n'

/** Adds `.ts` to relative import specifiers that do not already carry it. */
function addExtensions(source) {
  return source.replace(
    /(\bfrom\s+|\bimport\s+)(['"])(\.\.?\/[^'"]+?)\2/g,
    (match, kw, quote, spec) => (spec.endsWith('.ts') ? match : `${kw}${quote}${spec}.ts${quote}`),
  )
}

export function build() {
  const files = new Map()
  for (const rel of SOURCES) {
    const target = relative('lib', rel)
    files.set(target, HEADER + addExtensions(readFileSync(join(root, rel), 'utf8')))
  }
  return files
}

export function readGenerated() {
  const files = new Map()
  const walk = (dir, prefix = '') => {
    let entries
    try {
      entries = readdirSync(dir, { withFileTypes: true })
    } catch {
      return
    }
    for (const entry of entries) {
      const next = join(dir, entry.name)
      if (entry.isDirectory()) walk(next, `${prefix}${entry.name}/`)
      else files.set(`${prefix}${entry.name}`, readFileSync(next, 'utf8'))
    }
  }
  walk(outDir)
  return files
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  rmSync(outDir, { recursive: true, force: true })
  for (const [target, contents] of build()) {
    const path = join(outDir, target)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, contents)
  }
  console.log(`synced ${build().size} files to ${relative(root, outDir)}`)
}
